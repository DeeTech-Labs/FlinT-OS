#!/usr/bin/env python3
"""Bake antialiased Lato subsets into VLW arrays (Pillow required).

Usage: python3 tools/gen_clock_fonts.py --font-dir /path/to/lato
Generated files are committed; firmware builds do not need Pillow or TTF files.
"""
import argparse
import hashlib
import struct
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]


def bake(path, size, chars, name, directory=None):
    font = ImageFont.truetype(str(path), size)
    glyphs = []
    for char in sorted(set(chars)):
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        width, height = right - left, bottom - top
        image = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor='ls')
        advance = round(font.getlength(char))
        glyphs.append((ord(char), height, width, advance, -top, left, 0, image.tobytes()[:width*height]))
    ascent = max(g[4] for g in glyphs)
    descent = max(g[1] - g[4] for g in glyphs)
    blob = struct.pack('>6i', len(glyphs), 11, size, 0, ascent, descent)
    blob += b''.join(struct.pack('>7i', *g[:7]) for g in glyphs)
    blob += b''.join(g[7] for g in glyphs)
    lines = ['// Generated by tools/gen_clock_fonts.py. Lato subset: SIL OFL 1.1.',
             f'// Source SHA256: {hashlib.sha256(path.read_bytes()).hexdigest()}',
             f'alignas(4) static const uint8_t {name}[] = {{']
    lines += ['  ' + ', '.join(f'0x{v:02x}' for v in blob[i:i+20]) + ',' for i in range(0, len(blob), 20)]
    lines += ['};', '']
    output = (directory or ROOT / 'components/flint/display/fonts') / (name + '.inc')
    output.write_text('\n'.join(lines))
    print(f'{output.name}: {len(blob)} bytes, {len(glyphs)} glyphs, {size}px')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-dir', required=True, type=Path)
    args = parser.parse_args()
    bake(args.font_dir / 'Lato-Bold.ttf', 34, 'FlinT?', 'flint_brand', ROOT / 'components/flint/render/fonts')
    numbers = '-0123456789:'
    bake(args.font_dir / 'Lato-Light.ttf', 80, numbers, 'flint_time_large')
    bake(args.font_dir / 'Lato-Light.ttf', 62, numbers, 'flint_time_compact')
    body = ''.join(chr(c) for c in range(32, 127)) + ''.join(chr(c) for c in range(0x410, 0x450)) + 'Ёё°—–…·→←'
    bake(args.font_dir / 'Lato-Regular.ttf', 20, body, 'flint_body')


if __name__ == '__main__':
    main()
