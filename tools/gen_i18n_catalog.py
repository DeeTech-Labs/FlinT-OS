#!/usr/bin/env python3
"""Generate components/flint/i18n/i18n_catalog.inc from flint.pot + locale .po files.

: msgid is the stable English key; msgstr is the translation.
lang_map.json points each locale at its flint.po (see i18n/lang/*/lang_map.json).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANG_DIR = ROOT / "components" / "flint" / "i18n" / "lang"
OUT = ROOT / "components" / "flint" / "i18n" / "i18n_catalog.inc"

MSGID_RE = re.compile(r'^msgid\s+"(.*)"\s*$')
MSGSTR_RE = re.compile(r'^msgstr\s+"(.*)"\s*$')
CONT_RE = re.compile(r'^"(.*)"\s*$')


def unescape(s: str) -> str:
    return (
        s.replace(r"\\", "\\")
        .replace(r"\"", '"')
        .replace(r"\n", "\n")
        .replace(r"\t", "\t")
    )


def c_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def parse_po(path: Path) -> dict[str, str]:
    entries: dict[str, str] = {}
    msgid: str | None = None
    msgstr: str | None = None
    mode = None

    def commit():
        nonlocal msgid, msgstr
        if msgid is not None and msgid != "" and msgstr is not None:
            entries[msgid] = msgstr
        msgid = None
        msgstr = None

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = MSGID_RE.match(line)
        if m:
            commit()
            msgid = unescape(m.group(1))
            msgstr = None
            mode = "id"
            continue
        m = MSGSTR_RE.match(line)
        if m:
            msgstr = unescape(m.group(1))
            mode = "str"
            continue
        m = CONT_RE.match(line)
        if m and mode == "id" and msgid is not None:
            msgid += unescape(m.group(1))
        elif m and mode == "str" and msgstr is not None:
            msgstr += unescape(m.group(1))
    commit()
    return entries


def msgids_from_pot(path: Path) -> list[str]:
    # Preserve order from .pot (skip header empty msgid).
    ordered: list[str] = []
    seen: set[str] = set()
    for mid in parse_po(path):
        if mid and mid not in seen:
            seen.add(mid)
            ordered.append(mid)
    return ordered


def enum_name(msgid: str, used: set[str]) -> str:
    # "Waiting for time" -> WaitingForTime; "p/n  Enter  Esc" -> PNEnterEsc
    cleaned = re.sub(r"[^A-Za-z0-9+]+", " ", msgid).strip()
    parts = cleaned.replace("+", "Plus").split()
    if not parts:
        name = "Empty"
    else:
        name = "".join(p[:1].upper() + p[1:] for p in parts)
        if name[0].isdigit():
            name = "N" + name
    base = name
    n = 2
    while name in used:
        name = f"{base}{n}"
        n += 1
    used.add(name)
    return name


def main() -> int:
    pot = LANG_DIR / "flint.pot"
    if not pot.is_file():
        print(f"missing {pot}", file=sys.stderr)
        return 1

    msgids = msgids_from_pot(pot)
    locales = [
        ("en_US", LANG_DIR / "en_US" / "flint.po"),
        ("ru_RU", LANG_DIR / "ru_RU" / "flint.po"),
    ]

    catalogs: dict[str, dict[str, str]] = {}
    for code, path in locales:
        if not path.is_file():
            print(f"missing {path}", file=sys.stderr)
            return 1
        catalogs[code] = parse_po(path)
        missing = [m for m in msgids if m not in catalogs[code]]
        if missing:
            print(f"{code}: missing {len(missing)} msgids (using English fallback)")

    used_names: set[str] = set()
    enum_names = [enum_name(mid, used_names) for mid in msgids]

    lines: list[str] = []
    lines.append("// Auto-generated by tools/gen_i18n_catalog.py — do not edit by hand.")
    lines.append("// Source: components/flint/i18n/lang/*.po")
    lines.append("#pragma once")
    lines.append("")
    lines.append("enum class FlintStr : uint16_t {")
    for i, name in enumerate(enum_names):
        lines.append(f"  {name} = {i},")
    lines.append(f"  COUNT = {len(msgids)}")
    lines.append("};")
    lines.append("")
    lines.append("static const char* const kFlintStrMsgid[] = {")
    for mid in msgids:
        lines.append(f'  "{c_escape(mid)}",')
    lines.append("};")
    lines.append("")

    for code, _ in locales:
        cat = catalogs[code]
        arr = "kFlintStrEn" if code == "en_US" else "kFlintStrRu"
        lines.append(f"static const char* const {arr}[] = {{")
        for mid in msgids:
            text = cat.get(mid, mid)
            if not text:
                text = mid
            lines.append(f'  "{c_escape(text)}",')
        lines.append("};")
        lines.append("")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(msgids)} strings, {len(locales)} locales)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
